def test_upgrade_from_previous_real_revision_preserves_rows_and_json(
    tmp_path: Path,
) -> None:
    database_path = tmp_path / "previous.sqlite3"
    database_url = _database_url(database_path)
    config = build_alembic_config(database_url)
    command.upgrade(config, BASELINE_REVISION)

    connection = sqlite3.connect(database_path)
    try:
        connection.executescript(LEGACY_SNAPSHOT.read_text(encoding="utf-8"))
        connection.commit()
    finally:
        connection.close()
    before = _existing_data_snapshot(database_path)
    assert {row["kind"] for row in before["catalog_objects"]} == {
        "host",
        "system",
        "netzwerk",
        "service",
        "credential_reference",
        "runbook",
        "decision",
        "project",
    }
    system_before = next(
        row for row in before["catalog_objects"] if row["id"] == "legacy-system"
    )
    assert system_before["data_json"] == {
        "schema_version": 1,
        "future_field": {"keep": True},
        "tags": ["legacy", "future"],
    }

    command.upgrade(config, "head")

    after = _existing_data_snapshot(database_path)
    expected = json.loads(json.dumps(before))
    legacy_service = next(
        row for row in expected["catalog_objects"] if row["id"] == "legacy-service"
    )
    assert legacy_service["data_json"].pop("system_id") == "system:legacy-system"
    legacy_network = next(
        row for row in expected["catalog_objects"] if row["id"] == "legacy-network"
    )
    legacy_network["kind"] = "network"
    for audit_event in expected["audit_events"]:
        audit_event["summary"] = "legacy"
    assert after == expected
    command.check(config)
    assert check_database_revision(database_url) == HEAD_REVISION


