class _PragmaResult:
    def __init__(self, row: tuple[int] | None) -> None:
        self.row = row

    def fetchone(self) -> tuple[int] | None:
        return self.row


class _InstrumentedSQLiteConnection:
    def __init__(
        self,
        *,
        restoration_succeeds: bool = True,
        restoration_error: BaseException | None = None,
    ) -> None:
        self.foreign_keys_enabled = True
        self.in_transaction = False
        self.restoration_succeeds = restoration_succeeds
        self.restoration_error = restoration_error
        self.statements: list[str] = []

    def execute(self, statement: str) -> _PragmaResult:
        self.statements.append(statement)
        if statement == "PRAGMA foreign_key_check":
            return _PragmaResult(None)
        if statement == "PRAGMA foreign_keys=OFF":
            self.foreign_keys_enabled = False
            return _PragmaResult(None)
        if statement == "PRAGMA foreign_keys=ON":
            if self.restoration_error is not None:
                raise self.restoration_error
            if self.restoration_succeeds:
                self.foreign_keys_enabled = True
            return _PragmaResult(None)
        if statement == "PRAGMA foreign_keys":
            return _PragmaResult((int(self.foreign_keys_enabled),))
        if statement == "BEGIN":
            self.in_transaction = True
            return _PragmaResult(None)
        raise AssertionError(f"unexpected statement: {statement}")


class _InstrumentedMigrationEngine:
    def __init__(self, sqlite_connection: _InstrumentedSQLiteConnection) -> None:
        self.sqlite_connection = sqlite_connection
        self.disposed = False

    def connect(self) -> _InstrumentedMigrationConnection:
        return _InstrumentedMigrationConnection(self.sqlite_connection)

    def dispose(self) -> None:
        self.disposed = True


class _InstrumentedMigrationConnection:
    def __init__(self, sqlite_connection: _InstrumentedSQLiteConnection) -> None:
        self.connection = SimpleNamespace(driver_connection=sqlite_connection)
        self.dialect = SimpleNamespace(name="sqlite")

    def __enter__(self) -> _InstrumentedMigrationConnection:
        return self

    def __exit__(self, *_args: object) -> None:
        return None

    def begin(self) -> _InstrumentedMigrationTransaction:
        return _InstrumentedMigrationTransaction(self.connection.driver_connection)


class _InstrumentedMigrationTransaction:
    def __init__(self, sqlite_connection: _InstrumentedSQLiteConnection) -> None:
        self.sqlite_connection = sqlite_connection

    def __enter__(self) -> _InstrumentedMigrationTransaction:
        return self

    def __exit__(self, *_args: object) -> None:
        self.sqlite_connection.in_transaction = False


def _instrument_sqlite_migration_connection(
    monkeypatch: pytest.MonkeyPatch,
    *,
    restoration_succeeds: bool = True,
    restoration_error: BaseException | None = None,
) -> tuple[_InstrumentedSQLiteConnection, _InstrumentedMigrationEngine]:
    sqlite_connection = _InstrumentedSQLiteConnection(
        restoration_succeeds=restoration_succeeds,
        restoration_error=restoration_error,
    )
    engine = _InstrumentedMigrationEngine(sqlite_connection)
    monkeypatch.setattr("blockwart.db.session.build_engine", lambda _url: engine)
    return sqlite_connection, engine


def _database_url(path: Path) -> str:
    return f"sqlite:///{path}"


def _revision(database_url: str) -> str | None:
    engine = create_engine(database_url)
    try:
        with engine.connect() as connection:
            row = connection.execute(text("SELECT version_num FROM alembic_version")).one_or_none()
            return None if row is None else str(row.version_num)
    finally:
        engine.dispose()


def _create_unversioned_baseline(database_url: str) -> None:
    command.upgrade(build_alembic_config(database_url), BASELINE_REVISION)
    engine = create_engine(database_url)
    try:
        with engine.begin() as connection:
            connection.execute(text("DROP TABLE alembic_version"))
    finally:
        engine.dispose()


def _existing_data_snapshot(database_path: Path) -> dict[str, list[dict[str, object]]]:
    connection = sqlite3.connect(database_path)
    connection.row_factory = sqlite3.Row
    try:
        objects = []
        for row in connection.execute(
            "SELECT id, kind, label, status, summary, data_json, created_at, updated_at "
            "FROM catalog_objects ORDER BY id"
        ):
            payload = dict(row)
            payload["data_json"] = json.loads(str(payload["data_json"]))
            objects.append(payload)
        relationships = [
            dict(row)
            for row in connection.execute(
                "SELECT id, from_ref, relation_type, to_ref FROM relationships ORDER BY id"
            )
        ]
        audit_events = [
            dict(row)
            for row in connection.execute(
                "SELECT id, object_id, action, actor, summary, created_at "
                "FROM audit_events ORDER BY id"
            )
        ]
        return {
            "catalog_objects": objects,
            "relationships": relationships,
            "audit_events": audit_events,
        }
    finally:
        connection.close()


