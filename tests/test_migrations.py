def test_unversioned_baseline_adopts_before_real_future_migration(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    migrations_dir = tmp_path / "migrations"
    copytree(migration_module.MIGRATIONS_DIR, migrations_dir)
    future_revision = "20990101_0003"
    (migrations_dir / "versions" / f"{future_revision}_future_table.py").write_text(
        f'''"""synthetic future migration for the baseline-adoption contract"""

import sqlalchemy as sa
from alembic import op

revision = "{future_revision}"
down_revision = "{HEAD_REVISION}"
branch_labels = None
depends_on = None


def upgrade() -> None:
    op.create_table(
        "future_head_only",
        sa.Column("id", sa.Integer(), nullable=False),
        sa.PrimaryKeyConstraint("id"),
    )


def downgrade() -> None:
    op.drop_table("future_head_only")
''',
        encoding="utf-8",
    )
    monkeypatch.setattr(migration_module, "MIGRATIONS_DIR", migrations_dir)

    database_url = _database_url(tmp_path / "future-upgrade.sqlite3")
    _create_unversioned_baseline(database_url)
    engine = create_engine(database_url)
    with engine.begin() as connection:
        connection.execute(
            text(
                "INSERT INTO catalog_objects "
                "(id, kind, label, status, data_json) "
                "VALUES ('legacy', 'system', 'Legacy', 'active', '{}')"
            )
        )

    future_table = Table(
        "future_head_only",
        Base.metadata,
        Column("id", Integer, primary_key=True),
    )
    try:
        assert upgrade_database(database_url) == future_revision
        assert set(inspect(engine).get_table_names()) == {
            "alembic_version",
            "audit_events",
            "catalog_objects",
            "future_head_only",
            "relationships",
        }
        with engine.connect() as connection:
            assert connection.execute(
                text("SELECT label FROM catalog_objects WHERE id = 'legacy'")
            ).scalar_one() == "Legacy"
        assert _revision(database_url) == future_revision
    finally:
        Base.metadata.remove(future_table)
        engine.dispose()


