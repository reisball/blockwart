        assert "uplinks_to" in relationship_sql
        indexes = {
            row[1]: (row[2], row[4])
            for row in connection.execute("PRAGMA index_list('relationships')")
            if not row[1].startswith("sqlite_autoindex")
        }
        assert indexes == {
            "ix_relationships_from_ref": (0, 0),
            "ix_relationships_relation_type": (0, 0),
            "ix_relationships_to_ref": (0, 0),
            "uq_relationships_placement_parent": (1, 1),
        }
